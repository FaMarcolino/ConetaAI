SET client_min_messages = warning;

DROP TABLE IF EXISTS
    mensagem,
    estudante_area_interesse,
    estudante_tecnologia,
    vaga_tecnologia,
    vaga_curso,
    curtida,
    match,
    vaga,
    estudante,
    empresa,
    tecnologia,
    curso
CASCADE;

DROP FUNCTION IF EXISTS validar_match()             CASCADE;
DROP FUNCTION IF EXISTS vincular_curtidas_ao_match() CASCADE;
DROP FUNCTION IF EXISTS validar_curtida_do_match()   CASCADE;

-- Passo 1 do mapeamento: entidades regulares
-- Cursos e tecnologias são listas fechadas: o usuário escolhe, não digita.
CREATE TABLE curso (
    id    INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE tecnologia (
    id    INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE empresa (
    id         INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120) NOT NULL,
    email      VARCHAR(254) NOT NULL UNIQUE,
    senha      VARCHAR(255) NOT NULL,  -- hash scrypt da senha, nunca a senha em texto puro
    setor      VARCHAR(80)  NOT NULL,
    cidade     VARCHAR(80)  NOT NULL,
    descricao  TEXT,
    site       VARCHAR(200)
);

-- Passo 4 (1:N) já aplicado aqui: cursado_por -> estudante.curso_id
CREATE TABLE estudante (
    id                    INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(120) NOT NULL,
    email                 VARCHAR(254) NOT NULL UNIQUE,
    senha                 VARCHAR(255) NOT NULL,  -- hash scrypt da senha, nunca a senha em texto puro
    cidade                VARCHAR(80)  NOT NULL,
    modalidade            VARCHAR(10)  NOT NULL
                          CHECK (modalidade IN ('presencial', 'remoto', 'hibrido')),
    disponibilidade_meses INTEGER      NOT NULL CHECK (disponibilidade_meses >= 1),
    previsao_conclusao    VARCHAR(7)
                          CHECK (previsao_conclusao ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    curso_id              INTEGER      NOT NULL
                          REFERENCES curso (id) ON DELETE RESTRICT
);

-- Passo 4 (1:N): publica -> vaga.empresa_id
CREATE TABLE vaga (
    id                   INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cargo                VARCHAR(150) NOT NULL,
    modalidade           VARCHAR(10)  NOT NULL
                         CHECK (modalidade IN ('presencial', 'remoto', 'hibrido')),
    cidade               VARCHAR(80),
    faixa_salarial       VARCHAR(60),
    periodo_minimo_meses INTEGER      NOT NULL CHECK (periodo_minimo_meses >= 1),
    status               VARCHAR(10)  NOT NULL DEFAULT 'Ativa'
                         CHECK (status IN ('Ativa', 'Encerrada')),
    empresa_id           INTEGER      NOT NULL
                         REFERENCES empresa (id) ON DELETE CASCADE
);

-- Passo 4 (1:N): gera -> match.vaga_id e participa -> match.estudante_id
-- Um match por par (vaga, estudante). Os triggers mais abaixo garantem que ele só
-- exista quando há uma curtida de cada origem para esse par.
CREATE TABLE match (
    id           INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criado_em    TIMESTAMPTZ NOT NULL DEFAULT now(),
    estudante_id INTEGER     NOT NULL REFERENCES estudante (id) ON DELETE CASCADE,
    vaga_id      INTEGER     NOT NULL REFERENCES vaga (id)      ON DELETE CASCADE,
    UNIQUE (vaga_id, estudante_id)
);

-- Passo 4 (1:N): as duas ligações "curte" -> curtida.estudante_id e curtida.vaga_id
--                e o relacionamento "origina"  -> curtida.match_id
-- origem = 'estudante': o estudante curtiu a vaga
-- origem = 'empresa'  : a empresa dona da vaga curtiu o estudante para essa vaga
-- match_id é opcional: fica vazio até as duas curtidas formarem um match.
CREATE TABLE curtida (
    id           INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem       VARCHAR(10) NOT NULL CHECK (origem IN ('estudante', 'empresa')),
    criado_em    TIMESTAMPTZ NOT NULL DEFAULT now(),
    estudante_id INTEGER     NOT NULL REFERENCES estudante (id) ON DELETE CASCADE,
    vaga_id      INTEGER     NOT NULL REFERENCES vaga (id)      ON DELETE CASCADE,
    match_id     INTEGER     REFERENCES match (id) ON DELETE SET NULL,
    UNIQUE (estudante_id, vaga_id, origem),
    -- no máximo uma curtida de cada origem por match
    UNIQUE (match_id, origem)
);

-- Passo 4 (1:N): contem -> mensagem.match_id
CREATE TABLE mensagem (
    id          INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto       TEXT        NOT NULL CHECK (length(btrim(texto)) > 0),
    enviado_por VARCHAR(10) NOT NULL CHECK (enviado_por IN ('estudante', 'empresa')),
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT now(),
    match_id    INTEGER     NOT NULL REFERENCES match (id) ON DELETE CASCADE
);

-- Passo 5: relacionamentos M:N (uma relação nova para cada)

-- aceita: cada vaga aceita um ou mais cursos.
-- A exigência de "ao menos um curso" (participação 1,n) é verificada na aplicação.
CREATE TABLE vaga_curso (
    vaga_id  INTEGER NOT NULL REFERENCES vaga (id)  ON DELETE CASCADE,
    curso_id INTEGER NOT NULL REFERENCES curso (id) ON DELETE RESTRICT,
    PRIMARY KEY (vaga_id, curso_id)
);

-- requer
CREATE TABLE vaga_tecnologia (
    vaga_id       INTEGER NOT NULL REFERENCES vaga (id)       ON DELETE CASCADE,
    tecnologia_id INTEGER NOT NULL REFERENCES tecnologia (id) ON DELETE RESTRICT,
    PRIMARY KEY (vaga_id, tecnologia_id)
);

-- possui (habilidades do estudante)
CREATE TABLE estudante_tecnologia (
    estudante_id  INTEGER NOT NULL REFERENCES estudante (id)  ON DELETE CASCADE,
    tecnologia_id INTEGER NOT NULL REFERENCES tecnologia (id) ON DELETE RESTRICT,
    PRIMARY KEY (estudante_id, tecnologia_id)
);

-- Passo 6: atributo multivalorado (areas_interesse)
CREATE TABLE estudante_area_interesse (
    estudante_id INTEGER     NOT NULL REFERENCES estudante (id) ON DELETE CASCADE,
    area         VARCHAR(60) NOT NULL CHECK (length(btrim(area)) > 0),
    PRIMARY KEY (estudante_id, area)
);

-- Regra do match: "um match só existe quando há uma curtida de cada origem para o
-- mesmo par (estudante, vaga)". O modelo relacional não expressa isso apenas com
-- chaves, então é garantido por três triggers.

-- 1) Antes de criar (ou alterar o par de) um match, confere as duas curtidas.
CREATE FUNCTION validar_match() RETURNS trigger AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM curtida
                    WHERE estudante_id = NEW.estudante_id AND vaga_id = NEW.vaga_id
                      AND origem = 'estudante')
    OR NOT EXISTS (SELECT 1 FROM curtida
                    WHERE estudante_id = NEW.estudante_id AND vaga_id = NEW.vaga_id
                      AND origem = 'empresa') THEN
        RAISE EXCEPTION
            'Um match exige uma curtida de cada origem (estudante e empresa) para o mesmo par (estudante %, vaga %).',
            NEW.estudante_id, NEW.vaga_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_match_exige_curtidas
    BEFORE INSERT OR UPDATE OF estudante_id, vaga_id ON match
    FOR EACH ROW EXECUTE FUNCTION validar_match();

-- 2) Depois de criar o match, liga a ele as duas curtidas (relacionamento "origina").
CREATE FUNCTION vincular_curtidas_ao_match() RETURNS trigger AS $$
BEGIN
    UPDATE curtida
       SET match_id = NEW.id
     WHERE estudante_id = NEW.estudante_id
       AND vaga_id      = NEW.vaga_id;
    RETURN NULL;
END
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_match_vincula_curtidas
    AFTER INSERT ON match
    FOR EACH ROW EXECUTE FUNCTION vincular_curtidas_ao_match();

-- 3) Uma curtida só pode apontar para o match do seu próprio par (estudante, vaga).
CREATE FUNCTION validar_curtida_do_match() RETURNS trigger AS $$
BEGIN
    IF NEW.match_id IS NOT NULL AND NOT EXISTS (
           SELECT 1 FROM match
            WHERE id = NEW.match_id
              AND estudante_id = NEW.estudante_id
              AND vaga_id      = NEW.vaga_id) THEN
        RAISE EXCEPTION
            'A curtida (estudante %, vaga %) não pertence ao par do match %.',
            NEW.estudante_id, NEW.vaga_id, NEW.match_id
            USING ERRCODE = 'check_violation';
    END IF;
    RETURN NEW;
END
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_curtida_match_mesmo_par
    BEFORE INSERT OR UPDATE OF match_id ON curtida
    FOR EACH ROW EXECUTE FUNCTION validar_curtida_do_match();

