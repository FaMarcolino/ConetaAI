-- Restos da versão anterior deste esquema, que garantia a regra do match com triggers
-- (agora ela é garantida por chaves estrangeiras). Só limpa bancos criados antes.
DROP FUNCTION IF EXISTS validar_match()              CASCADE;
DROP FUNCTION IF EXISTS vincular_curtidas_ao_match() CASCADE;
DROP FUNCTION IF EXISTS validar_curtida_do_match()   CASCADE;

-- Passo 1 do mapeamento: entidades regulares
-- Cursos e tecnologias são listas fechadas: o usuário escolhe, não digita.
CREATE TABLE curso (
    id    INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(100) NOT NULL UNIQUE
);

CREATE TABLE tecnologia (
    id    INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome  VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE empresa (
    id         INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome       VARCHAR(120) NOT NULL,
    email      VARCHAR(254) NOT NULL UNIQUE,
    senha      VARCHAR(255) NOT NULL,  -- hash scrypt da senha, nunca a senha em texto puro
    setor      VARCHAR(80)  NOT NULL,
    cidade     VARCHAR(80)  NOT NULL,
    descricao  TEXT,
    site       VARCHAR(200)
);

-- Passo 4 (1:N) já aplicado aqui: cursado_por -> estudante.curso_id
CREATE TABLE estudante (
    id                    INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome                  VARCHAR(120) NOT NULL,
    email                 VARCHAR(254) NOT NULL UNIQUE,
    senha                 VARCHAR(255) NOT NULL,  -- hash scrypt da senha, nunca a senha em texto puro
    cidade                VARCHAR(80)  NOT NULL,
    modalidade            VARCHAR(10)  NOT NULL
                          CHECK (modalidade IN ('presencial', 'remoto', 'hibrido')),
    disponibilidade_meses INTEGER      NOT NULL CHECK (disponibilidade_meses >= 1),
    previsao_conclusao    VARCHAR(7)
                          CHECK (previsao_conclusao ~ '^[0-9]{4}-(0[1-9]|1[0-2])$'),
    curso_id              INTEGER      NOT NULL
                          REFERENCES curso (id) ON DELETE RESTRICT
);

-- Passo 4 (1:N): publica -> vaga.empresa_id
CREATE TABLE vaga (
    id                   INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cargo                VARCHAR(150) NOT NULL,
    modalidade           VARCHAR(10)  NOT NULL
                         CHECK (modalidade IN ('presencial', 'remoto', 'hibrido')),
    cidade               VARCHAR(80),
    faixa_salarial       VARCHAR(60),
    periodo_minimo_meses INTEGER      NOT NULL CHECK (periodo_minimo_meses >= 1),
    status               VARCHAR(10)  NOT NULL DEFAULT 'Ativa'
                         CHECK (status IN ('Ativa', 'Encerrada')),
    empresa_id           INTEGER      NOT NULL
                         REFERENCES empresa (id) ON DELETE CASCADE
);

-- Passo 4 (1:N): as duas ligações "curte" -> curtida.estudante_id e curtida.vaga_id
-- origem = 'estudante': o estudante curtiu a vaga
-- origem = 'empresa'  : a empresa dona da vaga curtiu o estudante para essa vaga
CREATE TABLE curtida (
    id           INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    origem       VARCHAR(10) NOT NULL CHECK (origem IN ('estudante', 'empresa')),
    criado_em    TIMESTAMPTZ NOT NULL DEFAULT now(),
    estudante_id INTEGER     NOT NULL REFERENCES estudante (id) ON DELETE CASCADE,
    vaga_id      INTEGER     NOT NULL REFERENCES vaga (id)      ON DELETE CASCADE,
    UNIQUE (estudante_id, vaga_id, origem),
    -- chave que as chaves estrangeiras do match referenciam: permite conferir, juntas,
    -- a curtida, a origem e o par (estudante, vaga)
    UNIQUE (id, origem, estudante_id, vaga_id)
);

-- Passo 3 (1:1) aplicado aos DOIS relacionamentos entre Match e Curtida:
--   origina_estudante  (o match nasce da curtida do estudante)
--   origina_empresa    (o match nasce da curtida da empresa)
-- Pelo algoritmo, a chave estrangeira fica na entidade com participação total (Match,
-- cardinalidade (1,1)), então ela é obrigatória: NÃO existe match sem as duas curtidas.
-- Cada curtida origina no máximo um match, por isso as duas colunas são UNIQUE.
--
-- As chaves estrangeiras são compostas e incluem a origem e o par (estudante, vaga):
--   * a curtida apontada por curtida_estudante_id precisa ter origem 'estudante';
--   * a curtida apontada por curtida_empresa_id precisa ter origem 'empresa';
--   * as duas precisam ser do mesmo (estudante_id, vaga_id) do match.
-- As colunas origem_curtida_* guardam sempre o mesmo valor fixo (o CHECK impede outro);
-- existem só para que a chave estrangeira composta consiga conferir a origem.
CREATE TABLE match (
    id                       INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    criado_em                TIMESTAMPTZ NOT NULL DEFAULT now(),
    estudante_id             INTEGER     NOT NULL,
    vaga_id                  INTEGER     NOT NULL,
    curtida_estudante_id     INTEGER     NOT NULL UNIQUE,
    curtida_empresa_id       INTEGER     NOT NULL UNIQUE,
    origem_curtida_estudante VARCHAR(10) NOT NULL DEFAULT 'estudante'
                             CHECK (origem_curtida_estudante = 'estudante'),
    origem_curtida_empresa   VARCHAR(10) NOT NULL DEFAULT 'empresa'
                             CHECK (origem_curtida_empresa = 'empresa'),
    -- Passo 4 (1:N): participa -> match.estudante_id e gera -> match.vaga_id
    -- (um match por par vaga/estudante)
    UNIQUE (vaga_id, estudante_id),
    CONSTRAINT fk_match_estudante FOREIGN KEY (estudante_id)
        REFERENCES estudante (id) ON DELETE CASCADE,
    CONSTRAINT fk_match_vaga FOREIGN KEY (vaga_id)
        REFERENCES vaga (id) ON DELETE CASCADE,
    -- se uma das curtidas for apagada, o match que dependia dela deixa de existir
    CONSTRAINT fk_match_curtida_estudante
        FOREIGN KEY (curtida_estudante_id, origem_curtida_estudante, estudante_id, vaga_id)
        REFERENCES curtida (id, origem, estudante_id, vaga_id) ON DELETE CASCADE,
    CONSTRAINT fk_match_curtida_empresa
        FOREIGN KEY (curtida_empresa_id, origem_curtida_empresa, estudante_id, vaga_id)
        REFERENCES curtida (id, origem, estudante_id, vaga_id) ON DELETE CASCADE
);

-- Passo 4 (1:N): contem -> mensagem.match_id
CREATE TABLE mensagem (
    id          INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    texto       TEXT        NOT NULL CHECK (length(btrim(texto)) > 0),
    enviado_por VARCHAR(10) NOT NULL CHECK (enviado_por IN ('estudante', 'empresa')),
    criado_em   TIMESTAMPTZ NOT NULL DEFAULT now(),
    match_id    INTEGER     NOT NULL REFERENCES match (id) ON DELETE CASCADE
);

-- Passo 5: relacionamentos M:N (uma relação nova para cada)

-- aceita: cada vaga aceita um ou mais cursos.
-- A exigência de "ao menos um curso" (participação 1,n) é verificada na aplicação.
CREATE TABLE vaga_curso (
    vaga_id  INTEGER NOT NULL REFERENCES vaga (id)  ON DELETE CASCADE,
    curso_id INTEGER NOT NULL REFERENCES curso (id) ON DELETE RESTRICT,
    PRIMARY KEY (vaga_id, curso_id)
);

-- requer
CREATE TABLE vaga_tecnologia (
    vaga_id       INTEGER NOT NULL REFERENCES vaga (id)       ON DELETE CASCADE,
    tecnologia_id INTEGER NOT NULL REFERENCES tecnologia (id) ON DELETE RESTRICT,
    PRIMARY KEY (vaga_id, tecnologia_id)
);

-- possui (habilidades do estudante)
CREATE TABLE estudante_tecnologia (
    estudante_id  INTEGER NOT NULL REFERENCES estudante (id)  ON DELETE CASCADE,
    tecnologia_id INTEGER NOT NULL REFERENCES tecnologia (id) ON DELETE RESTRICT,
    PRIMARY KEY (estudante_id, tecnologia_id)
);

-- Passo 6: atributo multivalorado (areas_interesse)
CREATE TABLE estudante_area_interesse (
    estudante_id INTEGER     NOT NULL REFERENCES estudante (id) ON DELETE CASCADE,
    area         VARCHAR(60) NOT NULL CHECK (length(btrim(area)) > 0),
    PRIMARY KEY (estudante_id, area)
);

